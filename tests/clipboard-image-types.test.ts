import { describe, expect, it } from 'vitest'
import {
  gifScreenSize,
  parseFileUriList,
  pickImageCandidateTypes,
  sniffImageMime
} from '../src/main/services/clipboard-image-types'

// 真实粘贴板形态样本（2026-10-08 微信复制图片实测，furl 抢占 W3C 类型后只剩原始格式）
const WECHAT_SHAPE = [
  'text/uri-list',
  'electron application/findtext',
  'electron application/osclipboard;format="Apple URL pasteboard type"',
  'electron application/osclipboard;format="CorePasteboardFlavorType 0x6675726C"',
  'electron application/osclipboard;format="NSFilenamesPboardType"',
  'electron application/osclipboard;format="NeXT TIFF v4.0 pasteboard type"',
  'electron application/osclipboard;format="TencentAttributeStringType"',
  'electron application/osclipboard;format="org.nspasteboard.AutoGeneratedType"'
]

describe('pickImageCandidateTypes', () => {
  it('纯 PNG 粘贴板：标准类型优先', () => {
    expect(pickImageCandidateTypes(['image/png', 'text/plain'])).toEqual(['image/png'])
  })

  it('微信形粘贴板：无任何 image/*，落到原始 TIFF 格式', () => {
    expect(pickImageCandidateTypes(WECHAT_SHAPE)).toEqual([
      'electron application/osclipboard;format="NeXT TIFF v4.0 pasteboard type"'
    ])
  })

  it('标准与原始格式并存时按 png → 其他 image/* → 原始格式排序', () => {
    const out = pickImageCandidateTypes([
      'electron application/osclipboard;format="NeXT TIFF v4.0 pasteboard type"',
      'image/jpeg',
      'image/png',
      'text/plain'
    ])
    expect(out).toEqual([
      'image/png',
      'image/jpeg',
      'electron application/osclipboard;format="NeXT TIFF v4.0 pasteboard type"'
    ])
  })

  it('非图片原始格式（furl/文本/动态 UTI）不进候选', () => {
    const out = pickImageCandidateTypes([
      'text/uri-list',
      'electron application/osclipboard;format="Apple URL pasteboard type"',
      'electron application/osclipboard;format="dyn.ah62d4rv4gu8y6y4grf0gn5xbrzw1gydcr7u1e3cytf2gn"',
      'text/plain'
    ])
    expect(out).toEqual([])
  })

  it('纯文本粘贴板返回空数组', () => {
    expect(pickImageCandidateTypes(['text/plain', 'text/html'])).toEqual([])
  })
})

// QQ 复制动图实测（2026-10-08）：GIF89a 原始字节塞在名叫 TIFF 的 flavor 里（字节与源文件逐字节同长）
const GIF_240 = new Uint8Array([
  0x47, 0x49, 0x46, 0x38, 0x39, 0x61, // GIF89a
  0xf0, 0x00, // width LE 240
  0xf0, 0x00, // height LE 240
  0x00, 0x00
])

describe('sniffImageMime', () => {
  it('识别五种白名单魔数', () => {
    expect(sniffImageMime(GIF_240)).toBe('image/gif')
    expect(sniffImageMime(new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))).toBe('image/png')
    expect(sniffImageMime(new Uint8Array([0xff, 0xd8, 0xff, 0xe0]))).toBe('image/jpeg')
    expect(sniffImageMime(new Uint8Array([0x42, 0x4d, 0x00, 0x00, 0x00, 0x00]))).toBe('image/bmp')
    expect(sniffImageMime(new Uint8Array([0x52, 0x49, 0x46, 0x46, 0, 0, 0, 0, 0x57, 0x45, 0x42, 0x50]))).toBe(
      'image/webp'
    )
  })

  it('GIF87a / TIFF / 短字节 / 乱字节不认', () => {
    expect(sniffImageMime(new Uint8Array([0x47, 0x49, 0x46, 0x38, 0x37, 0x61]))).toBe('image/gif')
    expect(sniffImageMime(new Uint8Array([0x49, 0x49, 0x2a, 0x00, 0x00, 0x00]))).toBeNull()
    expect(sniffImageMime(new Uint8Array([0x47, 0x49]))).toBeNull()
    expect(sniffImageMime(new Uint8Array(8))).toBeNull()
  })
})

describe('gifScreenSize', () => {
  it('读 GIF 头两个 LE u16（240×240 QQ 实测样本）', () => {
    expect(gifScreenSize(GIF_240)).toEqual({ width: 240, height: 240 })
  })

  it('非 GIF 返 null', () => {
    expect(gifScreenSize(new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0, 0, 3, 0, 4, 0]))).toBeNull()
  })
})

describe('parseFileUriList', () => {
  it('单条 file:// uri 解出本地路径（含 %20 转义）', () => {
    expect(parseFileUriList('file:///Users/a/b%20c/d.gif\r\n')).toBe('/Users/a/b c/d.gif')
    expect(parseFileUriList('#注释\r\nfile:///tmp/x.png')).toBe('/tmp/x.png')
  })

  it('多条 / 非 file 协议 / 空文本返 null', () => {
    expect(parseFileUriList('file:///a.png\r\nfile:///b.png')).toBeNull()
    expect(parseFileUriList('https://example.com/a.gif')).toBeNull()
    expect(parseFileUriList('')).toBeNull()
    expect(parseFileUriList('#只有注释')).toBeNull()
  })
})
