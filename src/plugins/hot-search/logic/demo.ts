/** demo 态各平台示例榜单（按 HOT_SOURCES 取数，id 漂移的平台自动缺省为空） */
export function demoBoards(now: number): Record<string, BoardData> {
  const out: Record<string, BoardData> = {}
  for (const s of HOT_SOURCES) {
    const items = DEMO_ITEMS[s.id]
    if (items !== undefined) out[s.id] = { fetchedAt: now, items }
  }
  return out
}
