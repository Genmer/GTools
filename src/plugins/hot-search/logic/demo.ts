type Row = [title: string, heat: number, tag?: string, isNew?: boolean]

function mk(rows: Row[]): HotItem[] {
  return rows.map(([title, heat, tag, isNew]) => ({
    key: title,
    title,
    url: `https://example.com/hot?q=${encodeURIComponent(title)}`,
    heat,
    ...(tag !== undefined ? { tag } : {}),
    ...(isNew === true ? { isNew: true } : {})
  }))
}

