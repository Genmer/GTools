/** 全角→半角、空白折叠后精确匹配；命中返回全部词条（多义项全收） */
export function lookupZhEn(normalized: string): ZhEnEntry[] {
  return ZH_EN.filter((e) => normalizeZh(e.zh) === normalized)
}

/** 归一化：trim + 全角空格/间隔号转半角 + 连续空白折叠为单空格 */
export function normalizeZh(input: string): string {
  return input
    .replace(/[\u3000\u00a0\u2007\u202f]/g, ' ')
    .replace(/[\uff01-\uff5e]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .trim()
    .replace(/\s+/g, ' ')
}
